const signed = (P) => { let a = 0; for (let i = 0; i < P.length; i++) { const [x0, y0] = P[i], [x1, y1] = P[(i + 1) % P.length]; a += x0 * y1 - x1 * y0; } return a / 2; };
// strictly inside a convex polygon (> eps from every edge line), or on it within eps
function side(P, x, y) {
  const o = Math.sign(signed(P));
  let min = Infinity;
  for (let i = 0; i < P.length; i++) {
    const [ax, ay] = P[i], [bx, by] = P[(i + 1) % P.length];
    min = Math.min(min, o * ((bx - ax) * (y - ay) - (by - ay) * (x - ax)) / Math.hypot(bx - ax, by - ay));
  }
  return min;          // > 0 inside, < 0 outside (signed distance to the nearest edge line, for a convex polygon)
}
const convex = (P) => { const o = Math.sign(signed(P)); return P.every((a, i) => { const b = P[(i + 1) % P.length], c = P[(i + 2) % P.length]; return ((b[0] - a[0]) * (c[1] - b[1]) - (b[1] - a[1]) * (c[0] - b[0])) * o > -1e-9; }); };

test('the face is this page\'s Classic Pro printing face; the usable area keeps 1.8 mm from every edge and the slits', () => {
  const v = JSON.parse(HTML.match(/const CP_BASE_VERTS = (\[.*?\]);/)[1]), t = JSON.parse(HTML.match(/const CP_BASE_TRIS = (\[.*?\]);/)[1]);
  let top = 0;                                     // the body's own printing face: every triangle at its top, z 1.5
  for (let i = 0; i < t.length; i += 3) {
    const [a, b, c] = [t[i], t[i + 1], t[i + 2]].map(k => v.slice(k * 3, k * 3 + 3));
    if ([a, b, c].every(p => p[2] === 1.5)) top += Math.abs((b[0] - a[0]) * (c[1] - a[1]) - (b[1] - a[1]) * (c[0] - a[0])) / 2;
  }
  assert.ok(Math.abs(Math.abs(signed(D.face)) - top) < 0.01, `face ${Math.abs(signed(D.face))} vs the body's top ${top}`);
  assert.ok(Math.abs(top - 1057.0) < 0.05, `top face ${top} mm²`);
  assert.equal(D.rules.margin, 1.8);
  assert.equal(D.align, 'centre');
  // the family icon before the value, on its mid-height, at the 7.2 mm compact size ("row 3": design review + Jerrari 2026-10-09)
  assert.deepEqual([D.iconSide, D.iconAlign, D.rules.iconVersion, D.rules.iconCompact], ['left', 'middle', 'compact', 7.2]);
  assert.ok(convex(D.usable), 'the usable hull is convex');
  assert.equal(D.cutouts.length, 2);
  for (const c of D.cutouts) {
    assert.ok(convex(c), 'a cutout is convex');
    // each cutout lies over a slit's side of the area and below its top, on the lower corner
    const xs = c.map(p => p[0]), ys = c.map(p => p[1]);
    assert.ok(Math.min(...xs.map(Math.abs)) > 19 && Math.max(...ys) < -1, `cutout at x ${Math.min(...xs)}..${Math.max(...xs)}, y up to ${Math.max(...ys)}`);
  }
  // the face's slits (their walls and round tops: the face edges between x 20.9 and 21.9, below y -2.5): no usable point
  // within 1.8 mm of them - sampled on a 0.05 mm grid over both lower corners, the area being the hull less the cutouts
  const slit = [];
  D.face.forEach((a, i) => {
    const b = D.face[(i + 1) % D.face.length], mx = Math.abs((a[0] + b[0]) / 2), my = (a[1] + b[1]) / 2;
    if (mx > 20.9 && mx < 21.9 && my < -2.5) slit.push([a, b]);
  });
  assert.ok(slit.length >= 10, `${slit.length} slit edges`);
  const toSeg = (x, y, [[ax, ay], [bx, by]]) => {
    const vx = bx - ax, vy = by - ay, L = vx * vx + vy * vy, t = Math.max(0, Math.min(1, ((x - ax) * vx + (y - ay) * vy) / L));
    return Math.hypot(ax + t * vx - x, ay + t * vy - y);
  };
  let nearest = Infinity, sampled = 0;
  for (let x = -20.5; x <= 20.5; x += 0.05) {
    if (Math.abs(x) < 18) continue;
    for (let y = -11; y <= 1; y += 0.05) {
      if (!(side(D.usable, x, y) > 1e-9 && D.cutouts.every(c => side(c, x, y) < -1e-9))) continue;
      sampled++;
      nearest = Math.min(nearest, ...slit.map(s => toSeg(x, y, s)));
    }
  }
  assert.ok(sampled > 1000 && nearest >= 1.8 - 1e-3, `nearest usable point to a slit ${nearest} mm (${sampled} sampled)`);
});

