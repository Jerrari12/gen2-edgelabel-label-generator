const rowOf = (k) => { let m = /^(?:main|beside)(\d+)$/.exec(k); if (m) return 'm' + m[1]; if (k === 'icon') return 'm1'; m = /^secondary(\d+)$/.exec(k); return m ? 's' + m[1] : k; };
function boxOf(parts) {
  let x0 = Infinity, y0 = Infinity, x1 = -Infinity, y1 = -Infinity;
  for (const rings of parts) for (const r of rings) for (let i = 0; i < r.length; i += 2) {
    x0 = Math.min(x0, r[i]); x1 = Math.max(x1, r[i]); y0 = Math.min(y0, r[i + 1]); y1 = Math.max(y1, r[i + 1]);
  }
  return [x0, y0, x1, y1];
}
function ringArea(r) { let a = 0; for (let i = 0, n = r.length; i < n; i += 2) { const j = (i + 2) % n; a += r[i] * r[j + 1] - r[j] * r[i + 1]; } return Math.abs(a / 2); }
function inRing(x, y, r) {
  let inside = false;
  for (let i = 0, n = r.length, j = n - 2; i < n; j = i, i += 2) {
    const xi = r[i], yi = r[i + 1], xj = r[j], yj = r[j + 1];
    if ((yi > y) !== (yj > y) && x < (xj - xi) * (y - yi) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}
function area(parts) { let a = 0; for (const rings of parts) for (const r of rings) a += (rings.filter(o => o !== r && inRing(r[0], r[1], o)).length % 2 ? -1 : 1) * ringArea(r); return a; }
const round = (x) => Math.round(x * 1e4) / 1e4;
function summary(r) {
  const rec = r.record;
  const out = { main_lines: rec.main_lines || null, main_cap: rec.main_cap || null, attributes: rec.attributes || null,
                attribute_places: rec.attribute_places || null, not_shown: rec.not_shown || null, icon: rec.icon || null,
                icon_left_off: rec.icon_left_off || null,
                nonfit: !!rec.nonfit, not_ready: !!rec.not_ready };
  if (r.elements) out.elements = Object.fromEntries(Object.entries(r.elements).map(([k, parts]) => [k, { bbox: boxOf(parts).map(round), area: round(area(parts)) }]));
  return out;
}
