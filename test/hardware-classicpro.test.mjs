test('every saved part item on Classic Pro: rows centred, inside the area and clear of the slits, as low as it fits', () => {
  const xs = D.usable.map(p => p[0]), ys = D.usable.map(p => p[1]);
  const XC = (Math.min(...xs) + Math.max(...xs)) / 2, top = Math.max(...ys), bottom = Math.min(...ys);
  let laid = 0;
  LAID.forEach((r, i) => {
    const id = `${FX.items[i].set} ${FX.items[i].id}`;
    if (!r.elements) return;
    laid++;
    const rows = {};
    for (const [k, parts] of Object.entries(r.elements)) {
      const b = boxOf(parts), rw = rows[rowOf(k)] || (rows[rowOf(k)] = [Infinity, -Infinity]);
      rw[0] = Math.min(rw[0], b[0]); rw[1] = Math.max(rw[1], b[2]);
      for (const rings of parts) for (const ring of rings) for (let j = 0; j < ring.length; j += 2) {
        assert.ok(side(D.usable, ring[j], ring[j + 1]) > -1e-6, `${id}: ${k} has a point outside the area`);
        for (const c of D.cutouts) assert.ok(side(c, ring[j], ring[j + 1]) <= 1e-9, `${id}: ${k} has a point inside the margin around a slit`);
      }
    }
    for (const [row, [x0, x1]] of Object.entries(rows)) assert.ok(Math.abs((x0 + x1) / 2 - XC) < 1e-9, `${id}: row ${row} is not centred`);
    const all = boxOf(Object.values(r.elements).flat());
    const above = top - all[3], below = all[1] - bottom;
    assert.ok(above <= below + 1e-6, `${id}: below the middle (${above} above, ${below} below)`);
    if (below - above > 0.01) {                    // held above the middle: 0.01 mm lower must not fit
      const lower = Object.fromEntries(Object.entries(r.elements).map(([k, parts]) => [k, parts.map(rings => rings.map(ring => ring.map((v, j) => j % 2 ? v - 0.01 : v)))]));
      assert.equal(CP._okRings(r.elements), true, `${id}: the label as laid out does not pass the layout's own check`);
      assert.equal(CP._okRings(lower), false, `${id}: is ${above.toFixed(3)} mm from the top and ${below.toFixed(3)} from the bottom, and 0.01 mm lower still fits`);
    }
  });
  assert.ok(laid >= 55, `${laid} laid out`);
});

